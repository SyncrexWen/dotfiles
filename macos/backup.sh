#!/usr/bin/env bash
# Read current values of keys listed in keys.list and generate defaults.sh
# Compatible with macOS system bash 3.2 (empty arrays are unsafe under set -u)
set -euo pipefail
cd "$(dirname "$0")"

OUT=defaults.sh
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

{
  echo '#!/usr/bin/env bash'
  echo '# Auto-generated by backup.sh. Do not edit by hand (edit keys.list and re-run backup instead).'
  echo 'set -u'
} > "$TMP"

count=0
while read -r domain key _; do
  [[ -z "${domain:-}" || "$domain" == \#* ]] && continue

  host=()
  prefix=""
  if [[ "$domain" == currentHost:* ]]; then
    host=(-currentHost)
    prefix="-currentHost "
    domain="${domain#currentHost:}"
  fi

  # Skip keys that do not exist (never configured on this machine)
  val=$(defaults ${host[@]+"${host[@]}"} read "$domain" "$key" 2>/dev/null) || continue
  type=$(defaults ${host[@]+"${host[@]}"} read-type "$domain" "$key" | awk '{print $3}')

  case "$type" in
    boolean) flag=-bool;   [[ "$val" == 1 ]] && val=true || val=false ;;
    integer) flag=-int ;;
    float)   flag=-float ;;
    string)  flag=-string ;;
    *) echo "Skipped (unsupported type '$type'): $domain $key" >&2; continue ;;
  esac

  if [[ "$type" == string ]]; then
    val=${val//"$HOME"/@@HOME@@}                 # parameterize home directory path
    val=$(printf '%s' "$val" | sed 's/[\\"$`]/\\&/g')
    val=${val//@@HOME@@/\$HOME}
    val="\"$val\""
  fi

  printf 'defaults %swrite %s %s %s %s\n' \
    "$prefix" "$domain" "$key" "$flag" "$val" >> "$TMP"
  count=$((count+1))
done < keys.list

# Privacy scan: abort if username, absolute home path, or email-like strings are found
if grep -nEi "/Users/|$(id -un)|@[a-z0-9-]+\." "$TMP"; then
  echo "[WARN] The lines above may contain private information. Aborted; $OUT was not written." >&2
  exit 1
fi

cp "$TMP" "$OUT"
chmod +x "$OUT"
echo "[OK] Backed up $count settings to macos/$OUT"
